#!/usr/bin/env python3
"""Step 6b - generate state-machine tests from a transition table.

A table plus "any transition not listed is forbidden" is a COMPLETE oracle:
  - transition tour : every listed transition is accepted
  - sneak path      : every unlisted (from, to) pair is rejected BY THE ACTION
Hand-writing these wastes effort and misses cases. Regenerate when the table changes.

Input: machines.yaml
  account:
    states: [active, suspended, deletion_requested, anonymised]
    terminal: [anonymised]
    transitions:
      - {from: active, to: suspended, trigger: "administrator suspends with a reason"}
"""
import sys, yaml, os

TEMPLATES = {
'pest': '''<?php
// GENERATED by pipeline/gen_transition_tests.py from machines.yaml - do not edit.
// Regenerate when the transition table changes.

use App\\Support\\StateMachines\\{Machine};

dataset('{name}_permitted', [
{permitted}
]);

dataset('{name}_forbidden', [
{forbidden}
]);

it('accepts every permitted {name} transition', function (string $from, string $to) {{
    expect({Machine}::allows($from, $to))->toBeTrue();
}})->with('{name}_permitted');

it('rejects every forbidden {name} transition at the action layer', function (string $from, string $to) {{
    expect(fn () => {Machine}::apply($from, $to))
        ->toThrow(\\App\\Support\\StateMachines\\ForbiddenTransition::class);
}})->with('{name}_forbidden');
''',
'pytest': '''# GENERATED by pipeline/gen_transition_tests.py from machines.yaml - do not edit.
import pytest
from app.state_machines import {Machine}, ForbiddenTransition

PERMITTED = [
{permitted}
]
FORBIDDEN = [
{forbidden}
]

@pytest.mark.parametrize("frm,to", PERMITTED)
def test_permitted_{name}(frm, to):
    assert {Machine}.allows(frm, to)

@pytest.mark.parametrize("frm,to", FORBIDDEN)
def test_forbidden_{name}(frm, to):
    with pytest.raises(ForbiddenTransition):
        {Machine}.apply(frm, to)
''',
'vitest': '''// GENERATED by pipeline/gen_transition_tests.py from machines.yaml - do not edit.
import {{ describe, it, expect }} from 'vitest';
import {{ {Machine}, ForbiddenTransition }} from '../src/stateMachines';

const permitted: [string, string][] = [
{permitted}
];
const forbidden: [string, string][] = [
{forbidden}
];

describe('{name} transitions', () => {{
  it.each(permitted)('accepts %s -> %s', (from, to) => {{
    expect({Machine}.allows(from, to)).toBe(true);
  }});
  it.each(forbidden)('rejects %s -> %s', (from, to) => {{
    expect(() => {Machine}.apply(from, to)).toThrow(ForbiddenTransition);
  }});
}});
''',
}
FMT = {'pest': '    ["{a}", "{b}"],', 'pytest': '    ("{a}", "{b}"),', 'vitest': "  ['{a}', '{b}'],"}

def generate(machines, flavour='pest', outdir='tests/Generated'):
    os.makedirs(outdir, exist_ok=True)
    written, counts = [], {}
    for name, m in machines.items():
        states = list(m['states'])
        listed = {(t['from'], t['to']) for t in m['transitions']}
        terminal = set(m.get('terminal', []))
        forbidden = [(a, b) for a in states for b in states
                     if a != b and (a, b) not in listed]
        # a terminal state must have no exit at all, including to itself
        forbidden += [(a, a) for a in terminal if (a, a) not in listed]
        row = FMT[flavour]
        body = TEMPLATES[flavour].format(
            name=name, Machine=''.join(p.capitalize() for p in name.split('_')) + 'Machine',
            permitted='\n'.join(row.format(a=a, b=b) for a, b in sorted(listed)),
            forbidden='\n'.join(row.format(a=a, b=b) for a, b in sorted(forbidden)))
        ext = {'pest': 'Test.php', 'pytest': '_test.py', 'vitest': '.test.ts'}[flavour]
        fn = os.path.join(outdir, f"{name}{ext}")
        open(fn, 'w').write(body); written.append(fn)
        counts[name] = (len(listed), len(forbidden))
    return written, counts

if __name__ == '__main__':
    src = sys.argv[1] if len(sys.argv) > 1 else 'machines.yaml'
    flav = sys.argv[2] if len(sys.argv) > 2 else 'pest'
    outd = sys.argv[3] if len(sys.argv) > 3 else 'tests/Generated'
    w, c = generate(yaml.safe_load(open(src)), flav, outd)
    tp = sum(v[0] for v in c.values()); tf = sum(v[1] for v in c.values())
    for n, (p, f) in c.items(): print(f"  {n:24s} {p:3d} permitted  {f:4d} sneak-path")
    print(f"generated {len(w)} file(s), {tp + tf} tests ({tp} permitted, {tf} forbidden)")
